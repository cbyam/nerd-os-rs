def body(path, signature):
    s = open(path).read()
    i = s.index(signature)
    j = s.index("{", i)
    depth = 0
    for k in range(j, len(s)):
        if s[k] == "{":
            depth += 1
        elif s[k] == "}":
            depth -= 1
            if depth == 0:
                return s[j : k + 1]
    raise ValueError(signature)


